/** Sentence case sem acento -- só usado quando o campo não está mapeado acima. */
function fallbackLabel(name: string): string {
  const words = name.toLowerCase().split("_").filter(Boolean);
  if (words.length === 0) return name;
  const [first, ...rest] = words;
  return [first.charAt(0).toUpperCase() + first.slice(1), ...rest].join(" ");
}

export function fieldLabel(fieldName: string): string {
  if (fieldName in FIELD_LABELS) return FIELD_LABELS[fieldName];
  if (fieldName.startsWith("ID_")) {
    const entity = fieldName.slice(3);
    if (entity in ENTITY_LABELS) return ENTITY_LABELS[entity];
    return fallbackLabel(entity);
  }
  return fallbackLabel(fieldName);
}
